using Content.Client._Floof.SubFloor; // FLOOF
using Content.Client.Markers;
using Content.Client.SubFloor;
using Content.Client.Stylesheets;
using Content.Shared.Atmos.Components; // FLOOF
using Content.Shared.Silicons.StationAi;
using Robust.Client.AutoGenerated;
using Robust.Client.Debugging;
using Robust.Client.Graphics;
using Robust.Client.Player;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.Sandbox.Windows;

[GenerateTypedNameReferences]
public sealed partial class SandboxWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entManager = null!;
    [Dependency] private IEyeManager _eyeManager = null!;
    [Dependency] private ILightManager _lightManager = null!;
    [Dependency] private IPlayerManager _playerManager = null!;
    private readonly DebugPhysicsSystem _debugPhysicsSystem;
    private readonly MarkerSystem _markerSystem;
    private readonly SubFloorHideSystem _subFloorSystem;

    public SandboxWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _debugPhysicsSystem = _entManager.System<DebugPhysicsSystem>();
        _markerSystem = _entManager.System<MarkerSystem>();
        _subFloorSystem = _entManager.System<SubFloorHideSystem>();

        SetupSubfloorFilter(); // FLOOF
    }

    protected override void Opened()
    {
        base.Opened();

        ToggleSubfloorButton.Pressed = _subFloorSystem.ShowAll;
        SyncSubfloorFilter(); // FLOOF
        ToggleLightButton.Pressed = !_lightManager.Enabled;
        ToggleFovButton.Pressed = !_eyeManager.CurrentEye.DrawFov;
        ToggleShadowsButton.Pressed = !_lightManager.DrawShadows;
        ShowMarkersButton.Pressed = _markerSystem.MarkersVisible;
        ShowBbButton.Pressed = (_debugPhysicsSystem.Flags & PhysicsDebugFlags.Shapes) != 0x0;
        AiOverlayButton.Pressed = _playerManager.LocalEntity is { } player && _entManager.HasComponent<StationAiOverlayComponent>(player);
    }

    // FLOOF - subfloor filter dropdowns
    // Item ids: the mode dropdown uses the SubFloorFilterMode value,
    // the layer dropdown uses -1 for "any layer" and the AtmosPipeLayer value otherwise.
    private const int AnyPipeLayerId = -1;

    private void SetupSubfloorFilter()
    {
        foreach (var mode in Enum.GetValues<SubFloorFilterMode>())
        {
            SubfloorModeOption.AddItem(Loc.GetString($"sandbox-window-subfloor-mode-{mode.ToString().ToLowerInvariant()}"), (int) mode);
        }

        SubfloorPipeLayerOption.AddItem(Loc.GetString("sandbox-window-subfloor-layer-any"), AnyPipeLayerId);
        foreach (var layer in Enum.GetValues<AtmosPipeLayer>())
        {
            SubfloorPipeLayerOption.AddItem(Loc.GetString($"sandbox-window-subfloor-layer-{layer.ToString().ToLowerInvariant()}"), (int) layer);
        }

        SubfloorModeOption.OnItemSelected += args =>
        {
            SubfloorModeOption.SelectId(args.Id);
            _subFloorSystem.ShowAllMode = (SubFloorFilterMode) args.Id;

            // Pipe layers only mean something for piping, so reset and disable the layer dropdown otherwise.
            if (_subFloorSystem.ShowAllMode != SubFloorFilterMode.Piping)
                _subFloorSystem.ShowAllPipeLayer = null;

            SyncSubfloorFilter();
        };

        SubfloorPipeLayerOption.OnItemSelected += args =>
        {
            SubfloorPipeLayerOption.SelectId(args.Id);
            _subFloorSystem.ShowAllPipeLayer = args.Id == AnyPipeLayerId ? null : (AtmosPipeLayer) args.Id;
        };
    }

    private void SyncSubfloorFilter()
    {
        SubfloorModeOption.SelectId((int) _subFloorSystem.ShowAllMode);
        SubfloorPipeLayerOption.SelectId(_subFloorSystem.ShowAllPipeLayer is { } layer ? (int) layer : AnyPipeLayerId);
        SubfloorPipeLayerOption.Disabled = _subFloorSystem.ShowAllMode != SubFloorFilterMode.Piping;
    }
    // FLOOF end
}
