using System.Linq;
using System.Text;
using Content.Client.Guidebook;
using Content.Client.Message;
using Content.Shared._Floof.Species;
using Content.Shared.Guidebook;
using Content.Shared.Humanoid.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Floof.Species.UI;

/// <summary>
/// Character editor tab showing a species' guidebook entry, a preview and a quick pros/cons overview.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SpeciesTab : BoxContainer
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private DocumentParsingManager _parsing = default!;

    public event Action<string>? OnSpeciesSelected;

    private readonly List<SpeciesPrototype> _species = new();
    private string? _shownSpecies;
    private EntityUid? _doll;

    public SpeciesTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SpeciesSelector.OnItemSelected += args =>
        {
            SpeciesSelector.SelectId(args.Id);
            OnSpeciesSelected?.Invoke(_species[args.Id].ID);
        };
    }

    /// <summary>
    /// Rebuilds the selector and shows the given species, if anything changed.
    /// </summary>
    public void SetSpecies(IReadOnlyList<SpeciesPrototype> species, string selected)
    {
        if (selected == _shownSpecies && species.Select(s => s.ID).SequenceEqual(_species.Select(s => s.ID)))
            return;

        _shownSpecies = selected;
        _species.Clear();
        _species.AddRange(species);

        SpeciesSelector.Clear();
        for (var i = 0; i < _species.Count; i++)
        {
            SpeciesSelector.AddItem(Loc.GetString(_species[i].Name), i);
            if (_species[i].ID == selected)
                SpeciesSelector.SelectId(i);
        }

        if (!_prototype.TryIndex<SpeciesPrototype>(selected, out var proto))
        {
            DeleteDoll();
            GuideContainer.RemoveAllChildren();
            OverviewLabel.SetMessage(string.Empty);
            return;
        }

        _prototype.TryIndex<SpeciesOverviewPrototype>(selected, out var overview);

        UpdatePreview(proto);
        UpdateGuide(overview?.GuideEntry ?? new ProtoId<GuideEntryPrototype>(selected));
        OverviewLabel.SetMarkup(
            $"[color=#90ee90][bold]{Loc.GetString("species-tab-pros")}[/bold][/color]\n{FormatList(overview?.Pros)}\n" +
            $"[color=#db7093][bold]{Loc.GetString("species-tab-cons")}[/bold][/color]\n{FormatList(overview?.Cons)}".TrimEnd());
    }

    private void UpdatePreview(SpeciesPrototype proto)
    {
        DeleteDoll();
        _doll = _entManager.Spawn(proto.DollPrototype);
        Preview.SetEntity(_doll);
    }

    private void UpdateGuide(ProtoId<GuideEntryPrototype> entry)
    {
        GuideContainer.RemoveAllChildren();

        if (_prototype.HasIndex(entry) && _parsing.TryAddMarkup(GuideContainer, entry))
            return;

        GuideContainer.AddChild(new Label
        {
            Text = Loc.GetString("species-tab-no-guide"),
            FontColorOverride = Color.Gray,
        });
    }

    private static string FormatList(List<LocId>? lines)
    {
        if (lines == null || lines.Count == 0)
            return $"[color=gray]{Loc.GetString("species-tab-none")}[/color]\n";

        var text = new StringBuilder();
        foreach (var line in lines)
            text.AppendLine(Loc.GetString("species-tab-entry", ("text", Loc.GetString(line))));
        return text.ToString();
    }

    private void DeleteDoll()
    {
        if (_doll is { } doll)
            _entManager.DeleteEntity(doll);
        _doll = null;
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        if (disposing)
            DeleteDoll();
    }
}
