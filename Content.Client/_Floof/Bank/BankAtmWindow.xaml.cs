using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Floof.Bank;

[GenerateTypedNameReferences]
public sealed partial class BankAtmWindow : FancyWindow
{
    public event Action<int>? OnWithdraw;

    public BankAtmWindow()
    {
        RobustXamlLoader.Load(this);
        AmountEdit.IsValid = text => text.Length == 0 || int.TryParse(text, out var n) && n > 0;
        WithdrawButton.OnPressed += _ => Submit();
        AmountEdit.OnTextEntered += _ => Submit();
    }

    private void Submit()
    {
        if (int.TryParse(AmountEdit.Text, out var amount) && amount > 0)
            OnWithdraw?.Invoke(amount);
    }

    public void UpdateState(int? balance)
    {
        BalanceLabel.Text = balance is { } b
            ? Loc.GetString("bank-atm-balance", ("balance", b))
            : Loc.GetString("bank-atm-no-account");
        AmountEdit.Editable = balance != null;
        WithdrawButton.Disabled = balance is null or 0;
    }
}
