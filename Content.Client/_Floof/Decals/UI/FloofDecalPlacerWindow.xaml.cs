using System.Linq;
using Content.Client.Decals.UI;
using Content.Client.Stylesheets;
using Content.Shared._Floof.Decals;
using Content.Shared.Decals;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Floof.Decals.UI;

/// <summary>
/// Floof decal placer: categorized decal list, fractional snapping and filtered erasing.
/// Based on the WizDen <see cref="DecalPlacerWindow"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class FloofDecalPlacerWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entMan = default!;

    private const string AllCategory = "__all";
    private const string OtherCategory = "__other";

    /// <summary>
    /// Step for the rotation field and the rotate keybind.
    /// </summary>
    private const float RotationStep = 90f;

    private readonly FloofDecalPlacementSystem _placement;
    private readonly SpriteSystem _sprite;

    public readonly FloatSpinBox RotationSpinBox;

    private PaletteColorPicker? _picker;

    private readonly Dictionary<string, DecalPrototype> _decals = new();
    private readonly Dictionary<string, Texture> _textures = new();
    private readonly List<(string Id, string Name, List<string> Decals)> _categories = new();
    private readonly ButtonGroup _categoryGroup = new();

    private string _selectedCategory = AllCategory;
    private string? _selected;
    private Color _color = Color.White;
    private bool _useColor;
    private float _rotation;
    private bool _cleanable;
    private int _zIndex;
    private bool _auto;

    public FloofDecalPlacerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _placement = _entMan.System<FloofDecalPlacementSystem>();
        _sprite = _entMan.System<SpriteSystem>();

        // Done in C# so we can pass a proper step size.
        RotationSpinBox = new FloatSpinBox(RotationStep, 0)
        {
            HorizontalExpand = true,
        };
        SpinBoxContainer.AddChild(RotationSpinBox);

        foreach (var divisions in FloofDecalPlacementSystem.SnapDivisionOptions)
        {
            var label = divisions switch
            {
                0 => Loc.GetString("floof-decal-placer-window-snap-off"),
                1 => Loc.GetString("floof-decal-placer-window-snap-tile"),
                _ => $"1/{divisions}",
            };
            SnapOption.AddItem(label, divisions);
        }
        SnapOption.SelectId(_placement.SnapDivisions);
        SnapOption.OnItemSelected += args =>
        {
            SnapOption.SelectId(args.Id);
            _placement.SnapDivisions = args.Id;
        };

        ShowGrid.Pressed = _placement.ShowGrid;
        ShowGrid.OnToggled += args => _placement.ShowGrid = args.Pressed;

        foreach (var mode in Enum.GetValues<DecalEraseMode>())
        {
            EraseModeOption.AddItem(Loc.GetString($"floof-decal-placer-window-erase-mode-{mode.ToString().ToLowerInvariant()}"), (int) mode);
        }
        EraseModeOption.SelectId((int) _placement.EraseMode);
        EraseModeOption.OnItemSelected += args =>
        {
            EraseModeOption.SelectId(args.Id);
            _placement.EraseMode = (DecalEraseMode) args.Id;
        };

        EraseOnlySelected.Pressed = _placement.EraseOnlySelected;
        EraseOnlySelected.OnToggled += args => _placement.EraseOnlySelected = args.Pressed;
        EraseOnlyColor.Pressed = _placement.EraseOnlyColor;
        EraseOnlyColor.OnToggled += args => _placement.EraseOnlyColor = args.Pressed;

        Search.OnTextChanged += _ => RefreshList();
        ColorPicker.OnColorChanged += OnColorPicked;

        PickerOpen.OnPressed += _ =>
        {
            if (_picker is null)
            {
                _picker = new PaletteColorPicker();
                _picker.OpenToLeft();
                _picker.PaletteList.OnItemSelected += args =>
                {
                    var color = (args.ItemList.GetSelected().First().Metadata as Color?)!.Value;
                    ColorPicker.Color = color;
                    OnColorPicked(color);
                };
            }
            else if (_picker.IsOpen)
            {
                _picker.Close();
            }
            else
            {
                _picker.Open();
            }
        };

        RotationSpinBox.OnValueChanged += args =>
        {
            _rotation = args.Value;
            UpdateDecalPlacementInfo();
        };
        EnableAuto.OnToggled += args =>
        {
            _auto = args.Pressed;
            if (_selected != null)
                SelectDecal(_selected);
        };
        EnableColor.OnToggled += args =>
        {
            _useColor = args.Pressed;
            UpdateDecalPlacementInfo();
            RefreshList();
        };
        EnableCleanable.OnToggled += args =>
        {
            _cleanable = args.Pressed;
            UpdateDecalPlacementInfo();
        };
        ZIndexSpinBox.ValueChanged += args =>
        {
            _zIndex = args.Value;
            UpdateDecalPlacementInfo();
        };

        UpdateSelectedLabel();
    }

    public void Populate(IEnumerable<DecalPrototype> decals, IEnumerable<DecalCategoryPrototype> categories)
    {
        _decals.Clear();
        _textures.Clear();
        _categories.Clear();

        foreach (var decal in decals)
        {
            if (!decal.ShowMenu)
                continue;

            _decals[decal.ID] = decal;
            _textures[decal.ID] = _sprite.Frame0(decal.Sprite);
        }

        var sortedIds = _decals.Keys.OrderBy(x => x, StringComparer.Ordinal).ToList();
        var categorized = new HashSet<string>();

        _categories.Add((AllCategory, Loc.GetString("floof-decal-placer-window-category-all"), sortedIds));

        foreach (var category in categories.OrderByDescending(x => x.Priority).ThenBy(x => Loc.GetString(x.Name)))
        {
            var ids = sortedIds.Where(id => category.Contains(_decals[id])).ToList();
            if (ids.Count == 0)
                continue;

            categorized.UnionWith(ids);
            _categories.Add((category.ID, Loc.GetString(category.Name), ids));
        }

        var other = sortedIds.Where(id => !categorized.Contains(id)).ToList();
        if (other.Count > 0)
            _categories.Add((OtherCategory, Loc.GetString("floof-decal-placer-window-category-other"), other));

        if (_categories.All(x => x.Id != _selectedCategory))
            _selectedCategory = AllCategory;

        RefreshCategories();
        RefreshList();
    }

    private void RefreshCategories()
    {
        CategoryList.RemoveAllChildren();

        foreach (var (id, name, decals) in _categories)
        {
            var button = new Button
            {
                Text = $"{name} ({decals.Count})",
                Group = _categoryGroup,
                Pressed = id == _selectedCategory,
                ClipText = true,
                ToolTip = name,
                StyleClasses = { StyleClass.ButtonOpenRight },
            };
            button.OnPressed += _ =>
            {
                _selectedCategory = id;
                RefreshList();
            };
            CategoryList.AddChild(button);
        }
    }

    private void RefreshList()
    {
        Grid.RemoveAllChildren();

        var category = _categories.FirstOrDefault(x => x.Id == _selectedCategory);
        if (category.Decals == null)
            return;

        var filter = Search.Text.Trim();
        foreach (var id in category.Decals)
        {
            if (filter.Length > 0 && !id.Contains(filter, StringComparison.OrdinalIgnoreCase))
                continue;

            var button = new TextureButton
            {
                TextureNormal = _textures[id],
                Name = id,
                ToolTip = id,
                Modulate = _useColor ? _color : Color.White,
            };
            button.OnPressed += _ => SelectDecal(id);

            if (_selected == id)
            {
                var panelContainer = new PanelContainer
                {
                    Children = { button },
                };
                panelContainer.SetOnlyStyleClass(StyleClass.PanelLight);
                Grid.AddChild(panelContainer);
            }
            else
            {
                Grid.AddChild(button);
            }
        }
    }

    private void OnRotateRequested()
    {
        // Keep the value in [0, 360) so repeated presses don't run off forever.
        _rotation = ((_rotation + RotationStep) % 360f + 360f) % 360f;
        RotationSpinBox.Value = _rotation;
        UpdateDecalPlacementInfo();
    }

    private void OnColorPicked(Color color)
    {
        _color = color;
        UpdateDecalPlacementInfo();
        RefreshList();
    }

    private void UpdateDecalPlacementInfo()
    {
        if (_selected is null)
            return;

        var color = _useColor ? _color : Color.White;
        _placement.UpdateDecalInfo(_selected, color, _rotation, _zIndex, _cleanable);
    }

    private void SelectDecal(string decalId)
    {
        if (!_decals.TryGetValue(decalId, out var decal))
            return;

        _selected = decalId;

        if (_auto)
        {
            EnableCleanable.Pressed = decal.DefaultCleanable;
            EnableColor.Pressed = decal.DefaultCustomColor;
            _cleanable = decal.DefaultCleanable;
            _useColor = decal.DefaultCustomColor;

            // Keep the chosen fraction if the decal wants snapping, just make sure something is selected.
            if (!decal.DefaultSnap)
                SetSnap(0);
            else if (_placement.SnapDivisions == 0)
                SetSnap(1);
        }

        UpdateDecalPlacementInfo();
        UpdateSelectedLabel();
        RefreshList();
    }

    private void SetSnap(int divisions)
    {
        _placement.SnapDivisions = divisions;
        SnapOption.SelectId(divisions);
    }

    private void UpdateSelectedLabel()
    {
        SelectedLabel.Text = _selected == null
            ? Loc.GetString("floof-decal-placer-window-none-selected")
            : Loc.GetString("floof-decal-placer-window-selected", ("decal", _selected));
    }

    protected override void Opened()
    {
        base.Opened();
        _placement.SetActive(true);
        _placement.RotateRequested += OnRotateRequested;
    }

    public override void Close()
    {
        base.Close();
        _placement.SetActive(false);
        _placement.RotateRequested -= OnRotateRequested;
        _picker?.Close();
    }
}
